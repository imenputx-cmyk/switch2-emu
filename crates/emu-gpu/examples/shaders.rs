//! Prints the test programs' Maxwell shaders as a C header
//! (tests/programs/libnx_compat/triangle_shaders.h):
//!
//!     cargo run -p emu-gpu --example shaders > tests/programs/libnx_compat/triangle_shaders.h

use emu_gpu::shader::asm::*;
use emu_gpu::shader::attr;

fn print(name: &str, code: &[u8]) {
    println!("static const u32 {name}[] __attribute__((aligned(256))) = {{");
    for (i, w) in code.chunks(4).enumerate() {
        if i % 8 == 0 {
            print!("   ");
        }
        print!(" 0x{:08x},", u32::from_le_bytes(w.try_into().unwrap()));
        if i % 8 == 7 {
            println!();
        }
    }
    println!("}};");
}

fn main() {
    println!("/* Generated by `cargo run -p emu-gpu --example shaders`. Maxwell shaders");
    println!(" * (0x50-byte header + code) for hb_triangle.c. */");
    // Vertex shader: position = attribute 0, varying 0 = attribute 1.
    let vs = program(
        &vertex_header(),
        &[
            ald(0, attr::generic(0), 4),
            ald(4, attr::generic(1), 4),
            ast(0, attr::POSITION, 4),
            ast(4, attr::generic(0), 4),
            exit(),
        ],
    );
    // Pixel shader: color = interpolated varying 0.
    let ps = program(
        &pixel_header(),
        &[
            ipa(0, attr::generic(0)),
            ipa(1, attr::generic(0) + 4),
            ipa(2, attr::generic(0) + 8),
            ipa(3, attr::generic(0) + 12),
            exit(),
        ],
    );
    print("vertex_shader", &vs);
    print("pixel_shader", &ps);
}
