/// A register's name: the block it is in and the offset inside it.
pub fn name(compute: bool, offset: u32) -> String {
    let table = if compute { COMPUTE } else { MAXWELL3D };
    let i = table.partition_point(|&(o, _)| o <= offset);
    if i == 0 {
        return format!("{offset:#x}");
    }
    let (base, n) = table[i - 1];
    match offset - base {
        0 => n.to_string(),
        d if d < 0x400 => format!("{n}+{d:#x}"),
        _ => format!("{offset:#x}"),
    }
}

/// Offset of the register with this name (a prefix match is enough when it
/// is unambiguous).
pub fn find(compute: bool, name: &str) -> Option<u32> {
    let table = if compute { COMPUTE } else { MAXWELL3D };
    if let Some(&(o, _)) = table.iter().find(|&&(_, n)| n == name) {
        return Some(o);
    }
    let mut hits = table.iter().filter(|&&(_, n)| n.starts_with(name));
    match (hits.next(), hits.next()) {
        (Some(&(o, _)), None) => Some(o),
        _ => None,
    }
}
